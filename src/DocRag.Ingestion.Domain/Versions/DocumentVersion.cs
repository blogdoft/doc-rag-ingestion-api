using BlogDoFT.Libs.ResultPattern;
using DocRag.Ingestion.Domain.Events;
using DocRag.Ingestion.Domain.Files;

namespace DocRag.Ingestion.Domain.Versions;

/// <summary>An editorial edition of a document and the reception state of its original file.</summary>
public sealed class DocumentVersion
{
    private readonly List<DocumentUploadedEvent> _events = [];

    private DocumentVersion()
    {
        Label = string.Empty;
    }

    /// <summary>Gets the internal surrogate key.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the internal key of the parent document.</summary>
    public long DocumentId { get; private set; }

    /// <summary>Gets the public identifier of the parent document.</summary>
    public Guid DocumentPublicId { get; private set; }

    /// <summary>Gets the editorial label, e.g. <c>4.00</c>.</summary>
    public string Label { get; private set; }

    /// <summary>Gets the publication date, when known.</summary>
    public DateTimeOffset? PublishedAt { get; private set; }

    /// <summary>Gets the start of validity, when known.</summary>
    public DateTimeOffset? EffectiveFrom { get; private set; }

    /// <summary>Gets the end of validity, when known.</summary>
    public DateTimeOffset? EffectiveTo { get; private set; }

    /// <summary>Gets the reception status.</summary>
    public IngestionStatus Status { get; private set; }

    /// <summary>Gets the registered original file, once uploaded.</summary>
    public DocumentFile? File { get; private set; }

    /// <summary>Gets the creation instant (UTC).</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>Gets the last update instant (UTC).</summary>
    public DateTimeOffset UpdatedAt { get; private set; }

    /// <summary>Gets the events raised by this instance and not yet dispatched.</summary>
    public IReadOnlyList<DocumentUploadedEvent> Events => _events;

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated version.</returns>
    public static DocumentVersion Rehydrate(
        long id,
        Guid publicId,
        long documentId,
        Guid documentPublicId,
        string label,
        DateTimeOffset? publishedAt,
        DateTimeOffset? effectiveFrom,
        DateTimeOffset? effectiveTo,
        IngestionStatus status,
        DocumentFile? file,
        DateTimeOffset createdAt,
        DateTimeOffset updatedAt) => new()
        {
            Id = id,
            PublicId = publicId,
            DocumentId = documentId,
            DocumentPublicId = documentPublicId,
            Label = label,
            PublishedAt = publishedAt,
            EffectiveFrom = effectiveFrom,
            EffectiveTo = effectiveTo,
            Status = status,
            File = file,
            CreatedAt = createdAt,
            UpdatedAt = updatedAt,
        };

    internal static DocumentVersion Create(
        Guid publicId,
        long documentId,
        Guid documentPublicId,
        string label,
        DateTimeOffset? publishedAt,
        DateTimeOffset? effectiveFrom,
        DateTimeOffset? effectiveTo,
        DateTimeOffset now) => new()
        {
            PublicId = publicId,
            DocumentId = documentId,
            DocumentPublicId = documentPublicId,
            Label = label,
            PublishedAt = publishedAt,
            EffectiveFrom = effectiveFrom,
            EffectiveTo = effectiveTo,
            Status = IngestionStatus.AwaitingUpload,
            CreatedAt = now,
            UpdatedAt = now,
        };

    /// <summary>Moves the version to <see cref="IngestionStatus.Uploading"/>.</summary>
    /// <param name="activeAttemptExists">Whether another attempt still holds a valid lease.</param>
    /// <param name="now">Current instant.</param>
    /// <returns>Success, or a <c>400</c> failure when a file already exists or another upload is running.</returns>
    public Result StartUpload(bool activeAttemptExists, DateTimeOffset now)
    {
        if (Status == IngestionStatus.Uploaded)
        {
            return new Failure("400-version-already-uploaded", "This version already has an original file; it cannot be replaced.");
        }

        if (activeAttemptExists)
        {
            return new Failure("400-upload-in-progress", "Another upload is already in progress for this version.");
        }

        Status = IngestionStatus.Uploading;
        UpdatedAt = now;
        return Result.AsSuccess();
    }

    /// <summary>Registers the stored file, finishes the ingestion and records the <see cref="DocumentUploadedEvent"/>.</summary>
    /// <param name="file">The stored file.</param>
    /// <param name="eventId">Identifier for the event.</param>
    /// <param name="correlationId">Request correlation identifier.</param>
    /// <param name="now">Current instant.</param>
    /// <returns>Success, or a <c>400</c> failure when the version is not uploading.</returns>
    public Result MarkUploaded(DocumentFile file, Guid eventId, string? correlationId, DateTimeOffset now)
    {
        if (Status != IngestionStatus.Uploading)
        {
            return new Failure("400-version-not-uploading", "The version is not receiving an upload.");
        }

        File = file;
        Status = IngestionStatus.Uploaded;
        UpdatedAt = now;
        _events.Add(new DocumentUploadedEvent(
            eventId,
            now,
            correlationId,
            DocumentPublicId,
            PublicId,
            file.PublicId,
            file.ContentType,
            file.SizeBytes,
            file.Sha256,
            file.Bucket,
            file.ObjectKey));
        return Result.AsSuccess();
    }

    /// <summary>Marks the last upload as failed so a new attempt can start; a no-op once uploaded.</summary>
    /// <param name="now">Current instant.</param>
    public void MarkUploadFailed(DateTimeOffset now)
    {
        if (Status != IngestionStatus.Uploading)
        {
            return;
        }

        Status = IngestionStatus.UploadFailed;
        UpdatedAt = now;
    }
}
