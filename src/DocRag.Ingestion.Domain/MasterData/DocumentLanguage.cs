using BlogDoFT.Libs.ResultPattern;
using DocRag.Ingestion.Domain.Common;
using FluentValidation;

namespace DocRag.Ingestion.Domain.MasterData;

/// <summary>Master data: a language a document can be written in.</summary>
public sealed class DocumentLanguage
{
    private DocumentLanguage()
    {
        Code = string.Empty;
    }

    /// <summary>Gets the internal surrogate key; never exposed publicly.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the BCP 47 language tag (e.g. <c>pt-BR</c>), unique ignoring case.</summary>
    public string Code { get; private set; }

    /// <summary>Gets the creation instant (UTC).</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>Gets the last update instant (UTC).</summary>
    public DateTimeOffset UpdatedAt { get; private set; }

    /// <summary>Starts a fluent factory.</summary>
    /// <returns>An empty builder.</returns>
    public static DocumentLanguageBuilder Builder() => new();

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated entity.</returns>
    public static DocumentLanguage Rehydrate(long id, Guid publicId, string code, DateTimeOffset createdAt, DateTimeOffset updatedAt) => new()
    {
        Id = id,
        PublicId = publicId,
        Code = code,
        CreatedAt = createdAt,
        UpdatedAt = updatedAt,
    };

    /// <summary>Changes the language tag.</summary>
    /// <param name="code">The new BCP 47 tag.</param>
    /// <param name="now">Current instant.</param>
    /// <returns>Success, or a <c>400</c> failure when the tag is invalid.</returns>
    public Result ChangeCode(string? code, DateTimeOffset now)
    {
        var normalized = code?.Trim();
        var validation = new DocumentLanguageValidator().Validate(normalized ?? string.Empty);
        if (!validation.IsValid)
        {
            return ValidationFailures.From("400-document-language-invalid", validation);
        }

        Code = normalized!;
        UpdatedAt = now;
        return Result.AsSuccess();
    }

    internal static DocumentLanguage Create(Guid publicId, string code, DateTimeOffset now) => new()
    {
        PublicId = publicId,
        Code = code,
        CreatedAt = now,
        UpdatedAt = now,
    };
}

/// <summary>Fluent factory that only yields a <see cref="DocumentLanguage"/> when every invariant holds.</summary>
public sealed class DocumentLanguageBuilder
{
    private Guid _publicId;
    private string? _code;

    /// <summary>Sets the public identifier (UUID v7, generated by the server).</summary>
    /// <param name="publicId">The identifier.</param>
    /// <returns>This builder.</returns>
    public DocumentLanguageBuilder WithPublicId(Guid publicId)
    {
        _publicId = publicId;
        return this;
    }

    /// <summary>Sets the language tag.</summary>
    /// <param name="code">The BCP 47 tag; surrounding whitespace is trimmed.</param>
    /// <returns>This builder.</returns>
    public DocumentLanguageBuilder WithCode(string? code)
    {
        _code = code?.Trim();
        return this;
    }

    /// <summary>Validates the collected state and builds the entity.</summary>
    /// <param name="now">Current instant, used as creation and update time.</param>
    /// <returns>The entity, or a failure describing the violated rules.</returns>
    public Result<DocumentLanguage> Build(DateTimeOffset now)
    {
        if (_publicId == Guid.Empty)
        {
            return new Failure("500-document-language-id-missing", "The document language identifier must be generated before building.");
        }

        var validation = new DocumentLanguageValidator().Validate(_code ?? string.Empty);
        return validation.IsValid
            ? DocumentLanguage.Create(_publicId, _code!, now)
            : ValidationFailures.From("400-document-language-invalid", validation);
    }
}

internal sealed class DocumentLanguageValidator : AbstractValidator<string?>
{
    public DocumentLanguageValidator()
    {
        RuleFor(code => code).NotEmpty().WithMessage("code is required.")
            .MaximumLength(35).WithMessage("code must have at most 35 characters.")
            .Matches(@"^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$").WithMessage("code must be a BCP 47 tag, e.g. pt-BR.");
    }
}
