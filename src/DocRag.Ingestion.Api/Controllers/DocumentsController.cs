using DocRag.Ingestion.Api.Authentication;
using DocRag.Ingestion.Api.Contracts;
using DocRag.Ingestion.Api.Extensions;
using DocRag.Ingestion.Api.Middleware;
using DocRag.Ingestion.Api.Problems;
using DocRag.Ingestion.Application.Common;
using DocRag.Ingestion.Application.Documents;
using DocRag.Ingestion.Domain.Documents;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace DocRag.Ingestion.Api.Controllers;

/// <summary>Logical identity and descriptive metadata of documents, independent of versions and files.</summary>
[ApiController]
[ApiExplorerSettings(GroupName = "documents")]
[Route("api/v1/documents")]
public sealed class DocumentsController(DocumentService documents) : ControllerBase
{
    /// <summary>Register a document</summary>
    /// <remarks>
    /// Creates the logical identity of a document. It does not create a version. The identifier is
    /// generated by the server (UUID v7).
    ///
    /// Send an <c>Idempotency-Key</c> (up to 128 characters) to retry safely: the same key with the
    /// same content returns the originally created document, the same key with different content
    /// returns <c>409</c>. Keys are scoped per operation.
    /// </remarks>
    /// <param name="request">The document to register.</param>
    /// <param name="idempotencyKey">Optional safe-retry key.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="201">Document registered; <c>Location</c> points to it and <c>ETag</c> carries its revision.</response>
    /// <response code="400">Malformed JSON or invalid field; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="409">The idempotency key was reused with different content, or is still being processed.</response>
    /// <response code="422">Well-formed but rejected by a business rule (e.g. metadata too large).</response>
    [HttpPost]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/json")]
    [ProducesResponseType<DocumentResponse>(StatusCodes.Status201Created, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, "application/problem+json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity, "application/problem+json")]
    public async Task<IActionResult> CreateAsync(
        [FromBody] CreateDocumentRequest request,
        [FromHeader(Name = "Idempotency-Key")][System.ComponentModel.DataAnnotations.StringLength(128, MinimumLength = 1)] string? idempotencyKey,
        CancellationToken cancellationToken)
    {
        var result = await documents.CreateAsync(
            new CreateDocumentCommand(
                idempotencyKey,
                request.Title,
                request.Description,
                request.Type,
                request.Language,
                request.Tags,
                request.Metadata),
            cancellationToken);

        if (result.IsFailure)
        {
            return result.Failure.ToActionResult(HttpContext);
        }

        Response.Headers.ETag = ETag(result.Value);
        return Created($"{Request.PathBase}/api/v1/documents/{result.Value.PublicId}", DocumentResponse.From(result.Value));
    }

    /// <summary>List documents</summary>
    /// <remarks>
    /// Documents, newest first, with opaque cursor pagination: pass the returned
    /// <c>nextCursor</c> as <c>cursor</c> to get the next page. <c>type</c>, <c>language</c> and
    /// <c>tag</c> are optional exact-match filters and <c>title</c> is a wildcard search; all combine with AND. Versions and files are not included.
    /// </remarks>
    /// <param name="type">Only documents of this category, e.g. <c>fiscal-manual</c>.</param>
    /// <param name="language">Only documents in this BCP 47 language, e.g. <c>pt-BR</c>.</param>
    /// <param name="tag">Only documents carrying this tag.</param>
    /// <param name="title">
    /// Case-insensitive title search, up to 300 characters. <c>*</c> matches any run of characters
    /// (<c>manual*</c> starts with, <c>*cte</c> ends with, <c>*fiscal*</c> contains); without any <c>*</c> the text
    /// must equal the whole title. Every other character is literal.
    /// </param>
    /// <param name="pageSize">Maximum items per page, 1 to 100 (default 20).</param>
    /// <param name="cursor">Opaque cursor from the previous page.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">A page of documents.</response>
    /// <response code="400">Invalid <c>pageSize</c> or <c>cursor</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    [HttpGet]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentPageResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> ListAsync(
        [FromQuery] string? type = null,
        [FromQuery] string? language = null,
        [FromQuery] string? tag = null,
        [FromQuery] string? title = null,
        [FromQuery] int pageSize = Pagination.DefaultPageSize,
        [FromQuery] string? cursor = null,
        CancellationToken cancellationToken = default)
    {
        var result = await documents.ListAsync(
            new DocumentFilter(type, language, tag, title), pageSize, cursor, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentPageResponse.From(result.Value));
    }

    /// <summary>Get a document</summary>
    /// <remarks>Returns the logical record without bytes or versions. The response carries the current <c>ETag</c>, required as <c>If-Match</c> to patch.</remarks>
    /// <param name="documentId">Document identifier (UUID).</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">The document.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpGet("{documentId:guid}")]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetAsync(Guid documentId, CancellationToken cancellationToken)
    {
        var result = await documents.GetAsync(documentId, cancellationToken);
        if (result.IsFailure)
        {
            return result.Failure.ToActionResult(HttpContext);
        }

        Response.Headers.ETag = ETag(result.Value);
        return Ok(DocumentResponse.From(result.Value));
    }

    /// <summary>Update document metadata</summary>
    /// <remarks>
    /// JSON Merge Patch (RFC 7396), media type <c>application/merge-patch+json</c>. Omitted members
    /// stay unchanged; <c>null</c> removes optional members (<c>description</c>) and, inside
    /// <c>metadata</c>, removes keys. <c>metadata</c> is merged recursively; <c>tags</c> is replaced.
    ///
    /// <c>If-Match</c> with the current ETag (quotes included) is mandatory to prevent lost updates:
    /// missing header → <c>428</c>, stale ETag → <c>412</c>. Versions and files are never changed by this call.
    /// </remarks>
    /// <param name="documentId">Document identifier.</param>
    /// <param name="request">The merge patch.</param>
    /// <param name="ifMatch">ETag from a previous GET, e.g. <c>"3"</c>. Required.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">Updated document with its new <c>ETag</c>.</response>
    /// <response code="400">Malformed JSON or invalid field; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    /// <response code="412">The ETag does not match the current revision.</response>
    /// <response code="422">The patched state violates a business rule.</response>
    /// <response code="428">The <c>If-Match</c> header is missing.</response>
    [HttpPatch("{documentId:guid}")]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/merge-patch+json")]
    [ProducesResponseType<DocumentResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status412PreconditionFailed, "application/problem+json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status422UnprocessableEntity, "application/problem+json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status428PreconditionRequired, "application/problem+json")]
    public async Task<IActionResult> PatchAsync(
        Guid documentId,
        [FromBody] PatchDocumentRequest request,
        [FromHeader(Name = "If-Match")] string? ifMatch,
        CancellationToken cancellationToken)
    {
        var result = await documents.PatchAsync(
            documentId, ParseRevision(ifMatch), request.ToPatch(), cancellationToken);
        if (result.IsFailure)
        {
            return result.Failure.ToActionResult(HttpContext);
        }

        Response.Headers.ETag = ETag(result.Value);
        return Ok(DocumentResponse.From(result.Value));
    }

    private static string ETag(Document document) => $"\"{document.Revision}\"";

    // A malformed value can never equal a revision, so it maps to the "stale" outcome (-1 never matches).
    private static long? ParseRevision(string? ifMatch)
    {
        if (string.IsNullOrWhiteSpace(ifMatch))
        {
            return null;
        }

        var value = ifMatch.Trim();
        if (value.StartsWith("W/", StringComparison.Ordinal))
        {
            value = value[2..];
        }

        return long.TryParse(value.Trim('"'), out var revision) ? revision : -1;
    }
}
