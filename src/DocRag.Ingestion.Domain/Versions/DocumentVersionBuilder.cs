using BlogDoFT.Libs.ResultPattern;
using FluentValidation;

namespace DocRag.Ingestion.Domain.Versions;

/// <summary>Fluent factory that only yields a <see cref="DocumentVersion"/> when every invariant holds.</summary>
public sealed class DocumentVersionBuilder
{
    private readonly Validator _validator = new();
    private Guid _publicId;
    private long _documentId;
    private Guid _documentPublicId;
    private string? _label;
    private DateTimeOffset? _publishedAt;
    private DateTimeOffset? _effectiveFrom;
    private DateTimeOffset? _effectiveTo;

    /// <summary>Starts a new builder.</summary>
    /// <returns>An empty builder.</returns>
    public static DocumentVersionBuilder New() => new();

    /// <summary>Sets the public identifier (UUID v7, generated by the server).</summary>
    /// <param name="publicId">The identifier.</param>
    /// <returns>This builder.</returns>
    public DocumentVersionBuilder WithPublicId(Guid publicId)
    {
        _publicId = publicId;
        return this;
    }

    /// <summary>Links the version to its document.</summary>
    /// <param name="documentId">Internal document key.</param>
    /// <param name="documentPublicId">Public document identifier.</param>
    /// <returns>This builder.</returns>
    public DocumentVersionBuilder ForDocument(long documentId, Guid documentPublicId)
    {
        _documentId = documentId;
        _documentPublicId = documentPublicId;
        return this;
    }

    /// <summary>Sets the editorial label.</summary>
    /// <param name="label">The label.</param>
    /// <returns>This builder.</returns>
    public DocumentVersionBuilder WithLabel(string? label)
    {
        _label = label;
        return this;
    }

    /// <summary>Sets the dates; absent values are kept absent, never inferred.</summary>
    /// <param name="publishedAt">Publication date.</param>
    /// <param name="effectiveFrom">Start of validity.</param>
    /// <param name="effectiveTo">End of validity.</param>
    /// <returns>This builder.</returns>
    public DocumentVersionBuilder WithDates(DateTimeOffset? publishedAt, DateTimeOffset? effectiveFrom, DateTimeOffset? effectiveTo)
    {
        _publishedAt = publishedAt;
        _effectiveFrom = effectiveFrom;
        _effectiveTo = effectiveTo;
        return this;
    }

    /// <summary>Validates the collected state and builds the version.</summary>
    /// <param name="now">Current instant.</param>
    /// <returns>The version, or a <c>422</c> failure describing the violated rules.</returns>
    public Result<DocumentVersion> Build(DateTimeOffset now)
    {
        if (_publicId == Guid.Empty || _documentId <= 0)
        {
            return new Failure("500-version-incomplete", "Document and identifier must be set before building a version.");
        }

        var validation = _validator.Validate(this);
        if (!validation.IsValid)
        {
            return new Failure("422-version-invalid", string.Join(" ", validation.Errors.Select(e => e.ErrorMessage)));
        }

        return DocumentVersion.Create(
            _publicId, _documentId, _documentPublicId, _label!, _publishedAt, _effectiveFrom, _effectiveTo, now);
    }

    private sealed class Validator : AbstractValidator<DocumentVersionBuilder>
    {
        public Validator()
        {
            RuleFor(x => x._label).NotEmpty().WithMessage("label is required.")
                .MaximumLength(100).WithMessage("label must have at most 100 characters.");
            RuleFor(x => x).Must(x => x._effectiveFrom is null || x._effectiveTo is null || x._effectiveTo >= x._effectiveFrom)
                .WithMessage("effectiveTo must not be earlier than effectiveFrom.");
        }
    }
}
