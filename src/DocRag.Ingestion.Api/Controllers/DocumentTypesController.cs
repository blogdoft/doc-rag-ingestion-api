using DocRag.Ingestion.Api.Authentication;
using DocRag.Ingestion.Api.Contracts;
using DocRag.Ingestion.Api.Extensions;
using DocRag.Ingestion.Api.Problems;
using DocRag.Ingestion.Application.Common;
using DocRag.Ingestion.Application.MasterData;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace DocRag.Ingestion.Api.Controllers;

/// <summary>Master data: the categories a document can be classified under.</summary>
[ApiController]
[ApiExplorerSettings(GroupName = "document-types")]
[Route("api/v1/document-types")]
public sealed class DocumentTypesController(DocumentTypeService documentTypes) : ControllerBase
{
    /// <summary>Register a document type</summary>
    /// <remarks>The identifier is generated by the server (UUID v7). Names are unique ignoring case.</remarks>
    /// <param name="request">The document type to register.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="201">Registered; <c>Location</c> points to it.</response>
    /// <response code="400">Malformed JSON, invalid name or a name that already exists; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    [HttpPost]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/json")]
    [ProducesResponseType<DocumentTypeResponse>(StatusCodes.Status201Created, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> CreateAsync([FromBody] DocumentTypeRequest request, CancellationToken cancellationToken)
    {
        var result = await documentTypes.CreateAsync(request.Name, cancellationToken);
        return result.IsFailure
            ? result.Failure.ToActionResult(HttpContext)
            : Created($"{Request.PathBase}/api/v1/document-types/{result.Value.PublicId}", DocumentTypeResponse.From(result.Value));
    }

    /// <summary>List document types</summary>
    /// <remarks>Newest first, with opaque cursor pagination: pass the returned <c>nextCursor</c> as <c>cursor</c> to get the next page.</remarks>
    /// <param name="pageSize">Maximum items per page, 1 to 100 (default 20).</param>
    /// <param name="cursor">Opaque cursor from the previous page.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">A page of document types.</response>
    /// <response code="400">Invalid <c>pageSize</c> or <c>cursor</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    [HttpGet]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentTypePageResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> ListAsync(
        [FromQuery] int pageSize = Pagination.DefaultPageSize,
        [FromQuery] string? cursor = null,
        CancellationToken cancellationToken = default)
    {
        var result = await documentTypes.ListAsync(pageSize, cursor, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentTypePageResponse.From(result.Value));
    }

    /// <summary>Get a document type</summary>
    /// <param name="documentTypeId">Document type identifier (UUID).</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">The document type.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpGet("{documentTypeId:guid}")]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentTypeResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetAsync(Guid documentTypeId, CancellationToken cancellationToken)
    {
        var result = await documentTypes.GetAsync(documentTypeId, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentTypeResponse.From(result.Value));
    }

    /// <summary>Replace a document type</summary>
    /// <remarks>Changes the name. Names are unique ignoring case.</remarks>
    /// <param name="documentTypeId">Document type identifier.</param>
    /// <param name="request">The new state.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">The updated document type.</response>
    /// <response code="400">Malformed JSON, invalid name or a name that already exists; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpPut("{documentTypeId:guid}")]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/json")]
    [ProducesResponseType<DocumentTypeResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> UpdateAsync(
        Guid documentTypeId,
        [FromBody] DocumentTypeRequest request,
        CancellationToken cancellationToken)
    {
        var result = await documentTypes.UpdateAsync(documentTypeId, request.Name, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentTypeResponse.From(result.Value));
    }

    /// <summary>Delete a document type</summary>
    /// <param name="documentTypeId">Document type identifier.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="204">Deleted.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpDelete("{documentTypeId:guid}")]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> DeleteAsync(Guid documentTypeId, CancellationToken cancellationToken)
    {
        var result = await documentTypes.DeleteAsync(documentTypeId, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : NoContent();
    }
}
