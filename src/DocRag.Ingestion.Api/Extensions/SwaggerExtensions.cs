using System.Text.Json;
using DocRag.Ingestion.Api.Authentication;
using DocRag.Ingestion.Api.Contracts;
using DocRag.Ingestion.Api.OpenApi;
using Microsoft.OpenApi;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace DocRag.Ingestion.Api.Extensions;

/// <summary>Swashbuckle OpenAPI document and Swagger UI.</summary>
public static class SwaggerExtensions
{
    /// <summary>Configuration key holding the externally reachable base URL (e.g. <c>https://host/prefix</c>).</summary>
    public const string PublicBaseUrlKey = "PublicBaseUrl";

    private const string ApiDescription = """
        Ingests and registers documents for the Doc RAG platform: logical document identity,
        editorial versions, streaming reception of the original file, durable storage in Garage (S3),
        and a `DocumentUploaded` event published to Kafka through a transactional outbox.

        **Recommended flow**
        1. `POST /api/v1/documents` - register the document.
        2. `POST /api/v1/documents/{documentId}/versions` - register a version.
        3. `POST /api/v1/documents/{documentId}/versions/{versionId}/files` - stream the original bytes.
        4. `GET  /api/v1/documents/{documentId}/versions/{versionId}` - read the ingestion status.

        **Success semantics:** `201` on upload means *stored, registered and queued in the outbox*. It
        does not mean Kafka delivered the event nor that conversion or indexing finished. Events are
        delivered at least once; consumers must deduplicate by `eventId`.

        **Authentication:** Bearer JWT.

        **Idempotency:** every POST accepts `Idempotency-Key` (up to 128 characters). The same key with
        the same content replays the original result; different content returns `400`. Keys are scoped
        per operation.

        **Formats:** JSON bodies use `application/json` (PATCH uses `application/merge-patch+json`) with
        camelCase properties; unknown properties are rejected. Uploads are raw binary bodies.

        **Errors:** `400` responses are RFC 9457
        `application/problem+json` with a `traceId`. `401`, `403`, `404` and `5xx` have no body.
        """;

    /// <summary>Registers Swashbuckle with XML comments, kebab-case tags, examples and the Bearer scheme.</summary>
    /// <param name="services">The service collection.</param>
    /// <returns>The same <paramref name="services"/>, for chaining.</returns>
    public static IServiceCollection AddSwaggerDocumentation(this IServiceCollection services)
    {
        services.AddSwaggerGen(options =>
        {
            options.SwaggerDoc("v1", new OpenApiInfo { Title = "Doc RAG Ingestion API", Version = AppVersion.Current, Description = ApiDescription });
            options.TagActionsBy(api => [api.GroupName ?? "default"]);
            options.DocInclusionPredicate((_, _) => true);
            options.IncludeXmlComments(Path.Combine(AppContext.BaseDirectory, "DocRag.Ingestion.Api.xml"), includeControllerXmlComments: true);

            options.MapType<PatchField<string>>(() => new OpenApiSchema { Type = JsonSchemaType.String | JsonSchemaType.Null });
            options.MapType<PatchField<List<string>>>(() => new OpenApiSchema
            {
                Type = JsonSchemaType.Array | JsonSchemaType.Null,
                Items = new OpenApiSchema { Type = JsonSchemaType.String },
            });
            options.MapType<PatchField<JsonElement?>>(() => new OpenApiSchema { Type = JsonSchemaType.Object | JsonSchemaType.Null });
            options.MapType<JsonElement>(() => new OpenApiSchema { Type = JsonSchemaType.Object });

            options.SchemaFilter<ExamplesSchemaFilter>();
            options.OperationFilter<IngestionOperationFilter>();
            options.DocumentFilter<SecurityDocumentFilter>();
            options.DocumentFilter<PublicServerDocumentFilter>();
        });

        return services;
    }

    /// <summary>
    /// Maps the OpenAPI document and Swagger UI at <c>/swagger</c>. When <c>PublicBaseUrl</c> has a path
    /// (a prefix the proxy strips before forwarding) it becomes the request path base, so redirects and
    /// links generated by Swagger UI keep the prefix.
    /// </summary>
    /// <param name="app">The web application.</param>
    /// <returns>The same <paramref name="app"/>, for chaining.</returns>
    public static WebApplication UseSwaggerDocumentation(this WebApplication app)
    {
        var publicPath = Uri.TryCreate(app.Configuration[PublicBaseUrlKey], UriKind.Absolute, out var publicUri)
            ? publicUri.AbsolutePath.TrimEnd('/')
            : string.Empty;
        if (publicPath.Length > 0)
        {
            app.Use((context, next) =>
            {
                context.Request.PathBase = publicPath;
                return next(context);
            });
        }

        app.UseSwagger(options => options.OpenApiVersion = OpenApiSpecVersion.OpenApi3_1);
        app.UseSwaggerUI(options =>
        {
            options.SwaggerEndpoint("v1/swagger.json", "Doc RAG Ingestion API v1");
            options.RoutePrefix = "swagger";
            options.DisplayRequestDuration();

            // "Authorize" redirects to the identity provider using the authorization code flow with PKCE
            // and a public client. The browser computes the redirect URI from the current page URL.
            var auth = app.Configuration.GetSection(AuthOptions.SectionName).Get<AuthOptions>();
            if (auth?.HasSwaggerLogin() == true)
            {
                options.OAuthClientId(auth.SwaggerClientId);
                options.OAuthUsePkce();
                options.OAuthScopes(auth.GetSwaggerScopes());
            }
        });

        return app;
    }
}
