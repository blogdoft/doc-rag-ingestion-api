using BlogDoFT.Libs.ResultPattern;

namespace DocRag.Ingestion.Domain.Files;

/// <summary>One attempt to receive a version's original file, guarded by a lease.</summary>
public sealed class UploadAttempt
{
    private UploadAttempt()
    {
        TemporaryObjectKey = string.Empty;
    }

    /// <summary>Gets the internal surrogate key.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the internal key of the version being uploaded.</summary>
    public long DocumentVersionId { get; private set; }

    /// <summary>Gets the pre-generated identifier the file will have if the attempt succeeds.</summary>
    public Guid FileId { get; private set; }

    /// <summary>Gets the current status.</summary>
    public UploadAttemptStatus Status { get; private set; }

    /// <summary>Gets the storage key the bytes are written to before being registered.</summary>
    public string TemporaryObjectKey { get; private set; }

    /// <summary>Gets the instant the lease runs out (UTC).</summary>
    public DateTimeOffset LeaseExpiresAt { get; private set; }

    /// <summary>Gets the bytes received so far or in total once finished.</summary>
    public long BytesReceived { get; private set; }

    /// <summary>Gets the failure code, when failed.</summary>
    public string? FailureCode { get; private set; }

    /// <summary>Gets the creation instant (UTC).</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>Starts an active attempt.</summary>
    /// <returns>The new attempt.</returns>
    public static UploadAttempt Start(
        Guid publicId,
        long documentVersionId,
        Guid fileId,
        string temporaryObjectKey,
        DateTimeOffset now,
        TimeSpan lease) => new()
        {
            PublicId = publicId,
            DocumentVersionId = documentVersionId,
            FileId = fileId,
            Status = UploadAttemptStatus.Active,
            TemporaryObjectKey = temporaryObjectKey,
            LeaseExpiresAt = now + lease,
            CreatedAt = now,
        };

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated attempt.</returns>
    public static UploadAttempt Rehydrate(
        long id,
        Guid publicId,
        long documentVersionId,
        Guid fileId,
        UploadAttemptStatus status,
        string temporaryObjectKey,
        DateTimeOffset leaseExpiresAt,
        long bytesReceived,
        string? failureCode,
        DateTimeOffset createdAt) => new()
        {
            Id = id,
            PublicId = publicId,
            DocumentVersionId = documentVersionId,
            FileId = fileId,
            Status = status,
            TemporaryObjectKey = temporaryObjectKey,
            LeaseExpiresAt = leaseExpiresAt,
            BytesReceived = bytesReceived,
            FailureCode = failureCode,
            CreatedAt = createdAt,
        };

    /// <summary>Marks the attempt as having produced the registered file.</summary>
    /// <param name="bytesReceived">Total bytes stored.</param>
    /// <returns>Success, or a failure when the attempt is no longer active.</returns>
    public Result Complete(long bytesReceived)
    {
        if (Status != UploadAttemptStatus.Active)
        {
            return new Failure("409-upload-attempt-not-active", "The upload attempt is no longer active (its lease may have expired).");
        }

        Status = UploadAttemptStatus.Completed;
        BytesReceived = bytesReceived;
        return Result.AsSuccess();
    }

    /// <summary>Marks the attempt as failed.</summary>
    /// <param name="failureCode">Stable failure code.</param>
    /// <param name="bytesReceived">Bytes received before the failure.</param>
    public void Fail(string failureCode, long bytesReceived)
    {
        if (Status != UploadAttemptStatus.Active)
        {
            return;
        }

        Status = UploadAttemptStatus.Failed;
        FailureCode = failureCode;
        BytesReceived = bytesReceived;
    }

    /// <summary>Whether the lease ran out at <paramref name="now"/> while the attempt was still active.</summary>
    /// <param name="now">Current instant.</param>
    /// <returns><see langword="true"/> when stale.</returns>
    public bool IsStale(DateTimeOffset now) => Status == UploadAttemptStatus.Active && LeaseExpiresAt <= now;
}
