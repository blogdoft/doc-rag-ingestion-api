using System.Text.Json;
using BlogDoFT.Libs.ResultPattern;
using DocRag.Ingestion.Domain.Common;

namespace DocRag.Ingestion.Domain.Documents;

/// <summary>Logical identity and descriptive metadata of a document, independent of its versions and files.</summary>
public sealed class Document
{
    private Document()
    {
        Title = string.Empty;
        Type = string.Empty;
        Language = string.Empty;
        Tags = [];
    }

    /// <summary>Gets the internal surrogate key; never exposed publicly.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the title.</summary>
    public string Title { get; private set; }

    /// <summary>Gets the optional description.</summary>
    public string? Description { get; private set; }

    /// <summary>Gets the category.</summary>
    public string Type { get; private set; }

    /// <summary>Gets the BCP 47 language tag.</summary>
    public string Language { get; private set; }

    /// <summary>Gets the tags.</summary>
    public IReadOnlyList<string> Tags { get; private set; }

    /// <summary>Gets the free-form metadata object.</summary>
    public JsonElement Metadata { get; private set; }

    /// <summary>Gets the optimistic-concurrency revision, starting at 1.</summary>
    public long Revision { get; private set; }

    /// <summary>Gets the creation instant (UTC).</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>Gets the last update instant (UTC).</summary>
    public DateTimeOffset UpdatedAt { get; private set; }

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated document.</returns>
    public static Document Rehydrate(
        long id,
        Guid publicId,
        string title,
        string? description,
        string type,
        string language,
        IReadOnlyList<string> tags,
        JsonElement metadata,
        long revision,
        DateTimeOffset createdAt,
        DateTimeOffset updatedAt) => new()
        {
            Id = id,
            PublicId = publicId,
            Title = title,
            Description = description,
            Type = type,
            Language = language,
            Tags = tags,
            Metadata = metadata,
            Revision = revision,
            CreatedAt = createdAt,
            UpdatedAt = updatedAt,
        };

    /// <summary>Applies a JSON Merge Patch, bumping the revision when it succeeds.</summary>
    /// <param name="patch">The patch to apply.</param>
    /// <param name="now">Current instant.</param>
    /// <returns>Success, or a <c>422</c> failure when the patched state would be invalid.</returns>
    public Result ApplyPatch(DocumentPatch patch, DateTimeOffset now)
    {
        var metadata = Metadata;
        if (patch.Metadata.IsSet)
        {
            metadata = patch.Metadata.Value is { ValueKind: JsonValueKind.Object } patchObject
                ? JsonMergePatch.Apply(Metadata, patchObject)
                : patch.Metadata.Value is null ? EmptyObject() : patch.Metadata.Value.Value;
        }

        var fields = new DocumentFields(
            patch.Title.IsSet ? patch.Title.Value : Title,
            patch.Description.IsSet ? patch.Description.Value : Description,
            patch.Type.IsSet ? patch.Type.Value : Type,
            patch.Language.IsSet ? patch.Language.Value : Language,
            patch.Tags.IsSet ? patch.Tags.Value ?? [] : Tags,
            metadata);

        var validation = new DocumentFieldsValidator().Validate(fields);
        if (!validation.IsValid)
        {
            return ValidationFailures.From("422-document-invalid", validation);
        }

        Title = fields.Title!;
        Description = fields.Description;
        Type = fields.Type!;
        Language = fields.Language!;
        Tags = fields.Tags;
        Metadata = fields.Metadata;
        Revision++;
        UpdatedAt = now;
        return Result.AsSuccess();
    }

    internal static JsonElement EmptyObject() => JsonSerializer.SerializeToElement(new { });

    internal static Document Create(Guid publicId, DocumentFields fields, DateTimeOffset now) => new()
    {
        PublicId = publicId,
        Title = fields.Title!,
        Description = fields.Description,
        Type = fields.Type!,
        Language = fields.Language!,
        Tags = fields.Tags,
        Metadata = fields.Metadata,
        Revision = 1,
        CreatedAt = now,
        UpdatedAt = now,
    };
}
