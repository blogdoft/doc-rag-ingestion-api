using DocRag.Ingestion.Api.Authentication;
using DocRag.Ingestion.Api.Contracts;
using DocRag.Ingestion.Api.Extensions;
using DocRag.Ingestion.Api.Problems;
using DocRag.Ingestion.Application.Common;
using DocRag.Ingestion.Application.MasterData;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace DocRag.Ingestion.Api.Controllers;

/// <summary>Master data: the languages a document can be written in.</summary>
[ApiController]
[ApiExplorerSettings(GroupName = "document-languages")]
[Route("api/v1/document-languages")]
public sealed class DocumentLanguagesController(DocumentLanguageService documentLanguages) : ControllerBase
{
    /// <summary>Register a document language</summary>
    /// <remarks>The identifier is generated by the server (UUID v7). Language tags (BCP 47) are unique ignoring case.</remarks>
    /// <param name="request">The document language to register.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="201">Registered; <c>Location</c> points to it.</response>
    /// <response code="400">Malformed JSON, invalid tag or a tag that already exists; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    [HttpPost]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/json")]
    [ProducesResponseType<DocumentLanguageResponse>(StatusCodes.Status201Created, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> CreateAsync([FromBody] DocumentLanguageRequest request, CancellationToken cancellationToken)
    {
        var result = await documentLanguages.CreateAsync(request.Code, cancellationToken);
        return result.IsFailure
            ? result.Failure.ToActionResult(HttpContext)
            : Created($"{Request.PathBase}/api/v1/document-languages/{result.Value.PublicId}", DocumentLanguageResponse.From(result.Value));
    }

    /// <summary>List document languages</summary>
    /// <remarks>Newest first, with opaque cursor pagination: pass the returned <c>nextCursor</c> as <c>cursor</c> to get the next page.</remarks>
    /// <param name="pageSize">Maximum items per page, 1 to 100 (default 20).</param>
    /// <param name="cursor">Opaque cursor from the previous page.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">A page of document languages.</response>
    /// <response code="400">Invalid <c>pageSize</c> or <c>cursor</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    [HttpGet]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentLanguagePageResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    public async Task<IActionResult> ListAsync(
        [FromQuery] int pageSize = Pagination.DefaultPageSize,
        [FromQuery] string? cursor = null,
        CancellationToken cancellationToken = default)
    {
        var result = await documentLanguages.ListAsync(pageSize, cursor, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentLanguagePageResponse.From(result.Value));
    }

    /// <summary>Get a document language</summary>
    /// <param name="documentLanguageId">Document language identifier (UUID).</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">The document language.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the read scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpGet("{documentLanguageId:guid}")]
    [Authorize(AuthenticationExtensions.ReadPolicy)]
    [ProducesResponseType<DocumentLanguageResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> GetAsync(Guid documentLanguageId, CancellationToken cancellationToken)
    {
        var result = await documentLanguages.GetAsync(documentLanguageId, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentLanguageResponse.From(result.Value));
    }

    /// <summary>Replace a document language</summary>
    /// <remarks>Changes the language tag. Language tags are unique ignoring case.</remarks>
    /// <param name="documentLanguageId">Document language identifier.</param>
    /// <param name="request">The new state.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="200">The updated document language.</response>
    /// <response code="400">Malformed JSON, invalid tag or a tag that already exists; see <c>errors</c>.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpPut("{documentLanguageId:guid}")]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [RequestSizeLimit(RequestLimits.JsonBodyBytes)]
    [Consumes("application/json")]
    [ProducesResponseType<DocumentLanguageResponse>(StatusCodes.Status200OK, "application/json")]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status400BadRequest, "application/problem+json")]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> UpdateAsync(
        Guid documentLanguageId,
        [FromBody] DocumentLanguageRequest request,
        CancellationToken cancellationToken)
    {
        var result = await documentLanguages.UpdateAsync(documentLanguageId, request.Code, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : Ok(DocumentLanguageResponse.From(result.Value));
    }

    /// <summary>Delete a document language</summary>
    /// <param name="documentLanguageId">Document language identifier.</param>
    /// <param name="cancellationToken">Propagates request abort.</param>
    /// <response code="204">Deleted.</response>
    /// <response code="401">Missing or invalid token. No body.</response>
    /// <response code="403">Token lacks the write scope. No body.</response>
    /// <response code="404">Not found. No body.</response>
    [HttpDelete("{documentLanguageId:guid}")]
    [Authorize(AuthenticationExtensions.WritePolicy)]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(StatusCodes.Status403Forbidden)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<IActionResult> DeleteAsync(Guid documentLanguageId, CancellationToken cancellationToken)
    {
        var result = await documentLanguages.DeleteAsync(documentLanguageId, cancellationToken);
        return result.IsFailure ? result.Failure.ToActionResult(HttpContext) : NoContent();
    }
}
