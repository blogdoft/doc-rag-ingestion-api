using System.Text.Json;
using BlogDoFT.Libs.ResultPattern;
using DocRag.Ingestion.Domain.Common;

namespace DocRag.Ingestion.Domain.Documents;

/// <summary>Fluent factory that only yields a <see cref="Document"/> when every invariant holds.</summary>
public sealed class DocumentBuilder
{
    private Guid _publicId;
    private string? _title;
    private string? _description;
    private string? _type;
    private string? _language;
    private IReadOnlyList<string> _tags = [];
    private JsonElement _metadata = Document.EmptyObject();

    /// <summary>Starts a new builder.</summary>
    /// <returns>An empty builder.</returns>
    public static DocumentBuilder New() => new();

    /// <summary>Sets the public identifier (UUID v7, generated by the server).</summary>
    /// <param name="publicId">The identifier.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder WithPublicId(Guid publicId)
    {
        _publicId = publicId;
        return this;
    }

    /// <summary>Sets the title.</summary>
    /// <param name="title">The title.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder WithTitle(string? title)
    {
        _title = title;
        return this;
    }

    /// <summary>Sets the description.</summary>
    /// <param name="description">The description.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder WithDescription(string? description)
    {
        _description = description;
        return this;
    }

    /// <summary>Sets the category.</summary>
    /// <param name="type">The category.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder OfType(string? type)
    {
        _type = type;
        return this;
    }

    /// <summary>Sets the language.</summary>
    /// <param name="language">A BCP 47 tag.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder InLanguage(string? language)
    {
        _language = language;
        return this;
    }

    /// <summary>Sets the tags.</summary>
    /// <param name="tags">The tags.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder WithTags(IEnumerable<string>? tags)
    {
        _tags = tags?.ToList() ?? [];
        return this;
    }

    /// <summary>Sets the metadata.</summary>
    /// <param name="metadata">A JSON object.</param>
    /// <returns>This builder.</returns>
    public DocumentBuilder WithMetadata(JsonElement? metadata)
    {
        _metadata = metadata ?? Document.EmptyObject();
        return this;
    }

    /// <summary>Validates the collected state and builds the document.</summary>
    /// <param name="now">Current instant, used as creation and update time.</param>
    /// <returns>The document, or a <c>422</c> failure describing the violated rules.</returns>
    public Result<Document> Build(DateTimeOffset now)
    {
        if (_publicId == Guid.Empty)
        {
            return new Failure("500-document-id-missing", "The document identifier must be generated before building.");
        }

        var fields = new DocumentFields(_title, _description, _type, _language, _tags, _metadata);
        var validation = new DocumentFieldsValidator().Validate(fields);
        return validation.IsValid
            ? Document.Create(_publicId, fields, now)
            : ValidationFailures.From("422-document-invalid", validation);
    }
}
