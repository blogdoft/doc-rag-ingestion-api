using Microsoft.OpenApi;
using Swashbuckle.AspNetCore.SwaggerGen;

namespace DocRag.Ingestion.Api.OpenApi;

/// <summary>
/// Documents what attributes cannot express: the raw binary upload body and its headers, the
/// correlation header accepted/returned by every operation, and the mandatory <c>If-Match</c> of PATCH.
/// </summary>
internal sealed class IngestionOperationFilter : IOperationFilter
{
    private static readonly string[] UploadMediaTypes =
    [
        "application/pdf",
        "text/markdown",
        "text/plain",
        "text/html",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    ];

    public void Apply(OpenApiOperation operation, OperationFilterContext context)
    {
        operation.Parameters ??= [];
        operation.Parameters.Add(new OpenApiParameter
        {
            Name = "X-Correlation-Id",
            In = ParameterLocation.Header,
            Required = false,
            Description = "Optional traceability identifier (up to 128 characters of letters, digits, '.', '_', ':' or '-'). Generated by the server when absent and always echoed in the response header of the same name.",
            Schema = new OpenApiSchema { Type = JsonSchemaType.String, MaxLength = 128 },
        });

        var method = context.ApiDescription.HttpMethod;
        var path = context.ApiDescription.RelativePath ?? string.Empty;

        if (method == "PATCH")
        {
            var ifMatch = operation.Parameters.FirstOrDefault(p => p.Name == "If-Match") as OpenApiParameter;
            if (ifMatch is not null)
            {
                ifMatch.Required = true;
                ifMatch.Description = "Current ETag of the document (quotes included), obtained from a previous GET or PATCH. A missing or stale value is answered with 400.";
                ifMatch.Example = System.Text.Json.Nodes.JsonValue.Create("\"3\"");
            }
        }

        if (method == "POST" && path.EndsWith("/files", StringComparison.Ordinal))
        {
            operation.Parameters.Add(new OpenApiParameter
            {
                Name = "Content-Disposition",
                In = ParameterLocation.Header,
                Required = true,
                Description = "Original file name, e.g. attachment; filename=\"manual.pdf\". Sanitized by the server and never used as a storage key.",
                Schema = new OpenApiSchema { Type = JsonSchemaType.String },
                Example = System.Text.Json.Nodes.JsonValue.Create("attachment; filename=\"MOC_CTe_VisaoGeral_v4.00.pdf\""),
            });

            var binary = new OpenApiSchema { Type = JsonSchemaType.String, Format = "binary" };
            operation.RequestBody = new OpenApiRequestBody
            {
                Required = true,
                Description = "Raw bytes of the original file (no multipart, no Base64). Chunked transfer encoding without Content-Length is supported. The Content-Type must be one of the enabled types and match the file's real signature.",
                Content = UploadMediaTypes.ToDictionary(type => type, _ => new OpenApiMediaType { Schema = binary }),
            };
        }
    }
}
