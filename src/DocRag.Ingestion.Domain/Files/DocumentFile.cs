using System.Text.RegularExpressions;
using BlogDoFT.Libs.ResultPattern;

namespace DocRag.Ingestion.Domain.Files;

/// <summary>The original file of a document version, once stored and registered.</summary>
public sealed partial class DocumentFile
{
    private DocumentFile()
    {
        OriginalName = string.Empty;
        ContentType = string.Empty;
        Sha256 = string.Empty;
        Bucket = string.Empty;
        ObjectKey = string.Empty;
    }

    /// <summary>Gets the internal surrogate key.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the internal key of the owning version.</summary>
    public long DocumentVersionId { get; private set; }

    /// <summary>Gets the sanitized original file name.</summary>
    public string OriginalName { get; private set; }

    /// <summary>Gets the validated MIME type.</summary>
    public string ContentType { get; private set; }

    /// <summary>Gets the exact number of bytes received.</summary>
    public long SizeBytes { get; private set; }

    /// <summary>Gets the lowercase hexadecimal SHA-256 digest.</summary>
    public string Sha256 { get; private set; }

    /// <summary>Gets the storage bucket; never exposed through the public API.</summary>
    public string Bucket { get; private set; }

    /// <summary>Gets the storage object key; never exposed through the public API.</summary>
    public string ObjectKey { get; private set; }

    /// <summary>Gets the instant the file became available (UTC).</summary>
    public DateTimeOffset UploadedAt { get; private set; }

    /// <summary>Builds a file record after a successful upload.</summary>
    /// <returns>The file, or a <c>422</c> failure when an invariant is violated.</returns>
    public static Result<DocumentFile> Create(
        Guid publicId,
        long documentVersionId,
        string originalName,
        string contentType,
        long sizeBytes,
        string sha256,
        string bucket,
        string objectKey,
        DateTimeOffset uploadedAt)
    {
        if (sizeBytes <= 0)
        {
            return new Failure("422-file-empty", "The uploaded file is empty.");
        }

        if (!Sha256Pattern().IsMatch(sha256))
        {
            return new Failure("422-file-sha256-invalid", "The SHA-256 digest must be 64 lowercase hexadecimal characters.");
        }

        if (string.IsNullOrWhiteSpace(originalName) || string.IsNullOrWhiteSpace(contentType)
            || string.IsNullOrWhiteSpace(bucket) || string.IsNullOrWhiteSpace(objectKey))
        {
            return new Failure("422-file-invalid", "File name, content type and storage location are required.");
        }

        return new DocumentFile
        {
            PublicId = publicId,
            DocumentVersionId = documentVersionId,
            OriginalName = originalName,
            ContentType = contentType,
            SizeBytes = sizeBytes,
            Sha256 = sha256,
            Bucket = bucket,
            ObjectKey = objectKey,
            UploadedAt = uploadedAt,
        };
    }

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated file.</returns>
    public static DocumentFile Rehydrate(
        long id,
        Guid publicId,
        long documentVersionId,
        string originalName,
        string contentType,
        long sizeBytes,
        string sha256,
        string bucket,
        string objectKey,
        DateTimeOffset uploadedAt) => new()
        {
            Id = id,
            PublicId = publicId,
            DocumentVersionId = documentVersionId,
            OriginalName = originalName,
            ContentType = contentType,
            SizeBytes = sizeBytes,
            Sha256 = sha256,
            Bucket = bucket,
            ObjectKey = objectKey,
            UploadedAt = uploadedAt,
        };

    [GeneratedRegex("^[a-f0-9]{64}$")]
    private static partial Regex Sha256Pattern();
}
