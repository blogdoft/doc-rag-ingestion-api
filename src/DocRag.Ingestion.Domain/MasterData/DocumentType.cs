using BlogDoFT.Libs.ResultPattern;
using DocRag.Ingestion.Domain.Common;
using FluentValidation;

namespace DocRag.Ingestion.Domain.MasterData;

/// <summary>Master data: a category a document can be classified under.</summary>
public sealed class DocumentType
{
    private DocumentType()
    {
        Name = string.Empty;
    }

    /// <summary>Gets the internal surrogate key; never exposed publicly.</summary>
    public long Id { get; private set; }

    /// <summary>Gets the public UUID v7 identifier.</summary>
    public Guid PublicId { get; private set; }

    /// <summary>Gets the category name, unique ignoring case.</summary>
    public string Name { get; private set; }

    /// <summary>Gets the creation instant (UTC).</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>Gets the last update instant (UTC).</summary>
    public DateTimeOffset UpdatedAt { get; private set; }

    /// <summary>Starts a fluent factory.</summary>
    /// <returns>An empty builder.</returns>
    public static DocumentTypeBuilder Builder() => new();

    /// <summary>Assigns the internal key generated by the database on insert.</summary>
    /// <param name="id">The generated key.</param>
    public void AssignId(long id)
    {
        if (Id != 0)
        {
            throw new InvalidOperationException("The internal key was already assigned.");
        }

        Id = id;
    }

    /// <summary>Rebuilds an entity from persisted state without re-validating it.</summary>
    /// <returns>The rehydrated entity.</returns>
    public static DocumentType Rehydrate(long id, Guid publicId, string name, DateTimeOffset createdAt, DateTimeOffset updatedAt) => new()
    {
        Id = id,
        PublicId = publicId,
        Name = name,
        CreatedAt = createdAt,
        UpdatedAt = updatedAt,
    };

    /// <summary>Changes the name.</summary>
    /// <param name="name">The new name.</param>
    /// <param name="now">Current instant.</param>
    /// <returns>Success, or a <c>400</c> failure when the name is invalid.</returns>
    public Result Rename(string? name, DateTimeOffset now)
    {
        var normalized = name?.Trim();
        var validation = new DocumentTypeValidator().Validate(normalized ?? string.Empty);
        if (!validation.IsValid)
        {
            return ValidationFailures.From("400-document-type-invalid", validation);
        }

        Name = normalized!;
        UpdatedAt = now;
        return Result.AsSuccess();
    }

    internal static DocumentType Create(Guid publicId, string name, DateTimeOffset now) => new()
    {
        PublicId = publicId,
        Name = name,
        CreatedAt = now,
        UpdatedAt = now,
    };
}

/// <summary>Fluent factory that only yields a <see cref="DocumentType"/> when every invariant holds.</summary>
public sealed class DocumentTypeBuilder
{
    private Guid _publicId;
    private string? _name;

    /// <summary>Sets the public identifier (UUID v7, generated by the server).</summary>
    /// <param name="publicId">The identifier.</param>
    /// <returns>This builder.</returns>
    public DocumentTypeBuilder WithPublicId(Guid publicId)
    {
        _publicId = publicId;
        return this;
    }

    /// <summary>Sets the category name.</summary>
    /// <param name="name">The name; surrounding whitespace is trimmed.</param>
    /// <returns>This builder.</returns>
    public DocumentTypeBuilder Named(string? name)
    {
        _name = name?.Trim();
        return this;
    }

    /// <summary>Validates the collected state and builds the entity.</summary>
    /// <param name="now">Current instant, used as creation and update time.</param>
    /// <returns>The entity, or a failure describing the violated rules.</returns>
    public Result<DocumentType> Build(DateTimeOffset now)
    {
        if (_publicId == Guid.Empty)
        {
            return new Failure("500-document-type-id-missing", "The document type identifier must be generated before building.");
        }

        var validation = new DocumentTypeValidator().Validate(_name ?? string.Empty);
        return validation.IsValid
            ? DocumentType.Create(_publicId, _name!, now)
            : ValidationFailures.From("400-document-type-invalid", validation);
    }
}

internal sealed class DocumentTypeValidator : AbstractValidator<string?>
{
    public DocumentTypeValidator()
    {
        RuleFor(name => name).NotEmpty().WithMessage("name is required.")
            .MaximumLength(100).WithMessage("name must have at most 100 characters.");
    }
}
